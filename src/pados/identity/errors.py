"""The closed identity error codes and their HTTP status (design §3.5)."""
from __future__ import annotations

from typing import Final

IDENTITY_DISABLED: Final = "IDENTITY_DISABLED"
PAIRING_CODE_INVALID: Final = "PAIRING_CODE_INVALID"
PAIRING_CODE_EXPIRED: Final = "PAIRING_CODE_EXPIRED"
PAIRING_RATE_LIMITED: Final = "PAIRING_RATE_LIMITED"
SESSION_REQUIRED: Final = "SESSION_REQUIRED"
SESSION_EXPIRED: Final = "SESSION_EXPIRED"
SESSION_REVOKED: Final = "SESSION_REVOKED"
CSRF_INVALID: Final = "CSRF_INVALID"
ORIGIN_NOT_ALLOWED: Final = "ORIGIN_NOT_ALLOWED"
DEVICE_NOT_FOUND: Final = "DEVICE_NOT_FOUND"
DEVICE_LIMIT: Final = "DEVICE_LIMIT"
IDENTITY_STORE_CORRUPT: Final = "IDENTITY_STORE_CORRUPT"
# Phase 2 (design §4): OIDC sign-in and PADOS actors.
OIDC_PROVIDER_NOT_CONFIGURED: Final = "OIDC_PROVIDER_NOT_CONFIGURED"
OIDC_CONFIG_INVALID: Final = "OIDC_CONFIG_INVALID"
OIDC_STATE_INVALID: Final = "OIDC_STATE_INVALID"
OIDC_PROVIDER_ERROR: Final = "OIDC_PROVIDER_ERROR"
OIDC_PROVIDER_UNAVAILABLE: Final = "OIDC_PROVIDER_UNAVAILABLE"
OIDC_CLIENT_CREDENTIAL_UNAVAILABLE: Final = "OIDC_CLIENT_CREDENTIAL_UNAVAILABLE"
OIDC_TOKEN_INVALID: Final = "OIDC_TOKEN_INVALID"
SSO_IDENTITY_NOT_BOUND: Final = "SSO_IDENTITY_NOT_BOUND"
ACTORS_CONFIG_INVALID: Final = "ACTORS_CONFIG_INVALID"
IDENTITY_PLAINTEXT_CREDENTIAL_FORBIDDEN: Final = "IDENTITY_PLAINTEXT_CREDENTIAL_FORBIDDEN"
ACTOR_ROLE_REQUIRED: Final = "ACTOR_ROLE_REQUIRED"

STATUS_BY_CODE: Final[dict[str, int]] = {
    IDENTITY_DISABLED: 404,
    PAIRING_CODE_INVALID: 403,
    PAIRING_CODE_EXPIRED: 403,
    PAIRING_RATE_LIMITED: 429,
    SESSION_REQUIRED: 403,
    SESSION_EXPIRED: 403,
    SESSION_REVOKED: 403,
    CSRF_INVALID: 403,
    ORIGIN_NOT_ALLOWED: 403,
    DEVICE_NOT_FOUND: 404,
    DEVICE_LIMIT: 409,
    IDENTITY_STORE_CORRUPT: 503,
    OIDC_PROVIDER_NOT_CONFIGURED: 404,
    OIDC_CONFIG_INVALID: 503,
    OIDC_STATE_INVALID: 403,
    OIDC_PROVIDER_ERROR: 502,
    OIDC_PROVIDER_UNAVAILABLE: 503,
    OIDC_CLIENT_CREDENTIAL_UNAVAILABLE: 503,
    OIDC_TOKEN_INVALID: 403,
    SSO_IDENTITY_NOT_BOUND: 403,
    ACTORS_CONFIG_INVALID: 503,
    IDENTITY_PLAINTEXT_CREDENTIAL_FORBIDDEN: 503,
    ACTOR_ROLE_REQUIRED: 403,
}


class IdentityError(Exception):
    """A refusal carrying one closed code; the message is the code itself, never request data."""

    def __init__(self, code: str) -> None:
        if code not in STATUS_BY_CODE:
            raise ValueError("unknown identity error code")
        super().__init__(code)
        self.code = code
        self.status_code = STATUS_BY_CODE[code]
