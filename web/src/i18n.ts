const catalogues: Record<Locale, Partial<Record<MessageKey, string>>> = { "zh-TW": zhTW, en };

export function hasMessage(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

/** The message in ``locale``, else English, else the key itself; ``{name}`` placeholders take ``params``. */
export function translate(locale: Locale, key: MessageKey, params: Params = {}): string {
  const template = catalogues[locale][key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}

export type Translate = (key: MessageKey, params?: Params) => string;

export const LocaleContext = createContext<Locale>(DEFAULT_LOCALE);

export function useT(): Translate {
  const locale = useContext(LocaleContext);
  return (key, params) => translate(locale, key, params);
}

export function englishKeys(): MessageKey[] {
  return Object.keys(en) as MessageKey[];
}

export function missingTranslations(locale: Locale): MessageKey[] {
  return englishKeys().filter((key) => catalogues[locale][key] === undefined);
}
